export function decodeEiuEmail(email: string): {
  isValidDomain: boolean;
  facultyCode: FacultyCode;
  facultyName: string;
  cohortYear: number | null;
  accountType: 'Sinh viên' | 'Cán bộ / Chuyên viên';
} {
  const normalized = email.trim().toLowerCase();
  const isValidDomain = normalized.endsWith('@eiu.edu.vn');
  const match = normalized.match(/\.(cit|bbs|set|sns)(\d{2})@eiu\.edu\.vn$/);

  if (match) {
    const rawFaculty = match[1].toUpperCase() as FacultyCode;
    const cohort = parseInt(match[2], 10);
    return {
      isValidDomain,
      facultyCode: rawFaculty,
      facultyName: FACULTY_METADATA[rawFaculty].nameVi,
      cohortYear: 2000 + cohort,
      accountType: 'Sinh viên',
    };
  }

  return {
    isValidDomain,
    facultyCode: 'OTHER',
    facultyName: FACULTY_METADATA.OTHER.nameVi,
    cohortYear: null,
    accountType: 'Cán bộ / Chuyên viên',
  };
}

export function decodeEiuStudentId(mssv: string): {
  isValid: boolean;
  enrollmentYear: string;
  degreeLevel: string;
  programType: string;
  majorCode: string;
  majorName: string;
  serialNumber: string;
} {
  const clean = mssv.trim();
  if (!/^\d{10}$/.test(clean)) {
    return {
      isValid: false,
      enrollmentYear: '-',
      degreeLevel: '-',
      programType: '-',
      majorCode: '-',
      majorName: 'Không áp dụng (Cán bộ / Chuyên viên)',
      serialNumber: '-',
    };
  }
  const yy = clean.slice(0, 2);
  const degree = clean.slice(2, 3);
  const mode = clean.slice(3, 4);
  const majorCode = clean.slice(4, 6);
  const serial = clean.slice(6, 10);

  const majorMap: Record<string, string> = {
    '10': 'Kỹ thuật Điều khiển và Tự động hóa',
    '12': 'Kỹ thuật Cơ điện tử',
    '14': 'Kỹ thuật Điện tử - Viễn thông',
    '15': 'Kỹ thuật Cơ khí',
    '20': 'Kỹ thuật phần mềm',
    '22': 'Mạng máy tính và truyền thông dữ liệu',
    '30': 'Quản trị kinh doanh',
    '31': 'Quản trị kinh doanh',
    '41': 'Quản trị kinh doanh / Kinh tế',
    '40': 'Điều dưỡng (Khoa Khoa học Sức khỏe)',
  };

  return {
    isValid: true,
    enrollmentYear: `20${yy}`,
    degreeLevel: degree === '3' ? 'Đại học (3)' : `Bậc ${degree}`,
    programType: mode === '1' || mode === '2' ? `Chính quy (${mode})` : `Hệ ${mode}`,
    majorCode,
    majorName: majorMap[majorCode] || `Mã ngành ${majorCode}`,
    serialNumber: serial,
  };
}

